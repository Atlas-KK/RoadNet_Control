// ============================================================
// 审计留痕领域类型（开发规格 MVP · FR-H1 / 产品方案 四·决策与审计库）
// 审计流「只增不改」：事件接入/归并、推理批次、版本流转、确认/打回/作废/证伪、
// 超时升级、LLM 调用与校验、数据集导出等关键动作均落一条不可变记录。
// ============================================================

export type AuditKind =
  | '事件接入'
  | '事件归并'
  | '事件拆分'
  | '事件证伪'
  | '事件处置闭环'
  | '人工续报'
  | '续报订正'
  | '推理批次'
  | '预案生成'
  | '预案确认'
  | '版本流转'
  | '措施确认'
  | '措施打回'
  | '预案作废'
  | '超时升级'
  | '最小安全动作'
  | 'LLM调用'
  | '数据集导出'
  | '演示案例';

/** 一条不可变审计记录。 */
export interface AuditEntry {
  /** 自增序号（持久化时由存储层赋值）。 */
  seq: number;
  /** 真实墙钟时间戳（ms）。 */
  tsReal: number;
  /** 模拟时钟当日秒（可选）。 */
  tsSim?: number;
  kind: AuditKind;
  eventId?: string;
  planId?: string;
  version?: number;
  /** 人类可读摘要。 */
  summary: string;
  /** 结构化载荷（得分明细、校验差异、理由等）。 */
  payload?: Record<string, unknown>;
}
