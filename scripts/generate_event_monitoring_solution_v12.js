function replaceText(oldText, newText) {
  if (!src.includes(oldText)) throw new Error(`未找到待替换内容: ${oldText.slice(0, 80)}`);
  src = src.replaceAll(oldText, newText);
}

function replaceSection(sectionTitle, replacementLine) {
  const escaped = sectionTitle.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`^c\\.push\\(h1\\('${escaped}'.*$`, 'm');
  if (!re.test(src)) throw new Error(`未找到章节生成代码: ${sectionTitle}`);
  src = src.replace(re, replacementLine);
}

